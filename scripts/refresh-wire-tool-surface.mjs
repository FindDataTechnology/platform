#!/usr/bin/env node
// scripts/refresh-wire-tool-surface.mjs — regenerate lib/wire-tool-risk.js from
// the two wire operation-MCP repos' tool-surface.json (add-wire-line-board,
// design D2).
//
// The single source of truth for a wire write tool's risk is the `tool_risk`
// top-level key of wire-ops-mcp/tool-surface.json and
// wire-build-mcp/tool-surface.json. paas cannot read those repos in CI, so this
// script vendors a snapshot module; the action registry is pinned to the
// snapshot by a CI test and the snapshot is pinned to the source files by a
// local test (scripts/test-wire-tool-risk.mjs) that skips when the checkouts
// are absent.
//
// Usage:
//   node scripts/refresh-wire-tool-surface.mjs           # rewrite snapshot; exit 2 if it changed
//   node scripts/refresh-wire-tool-surface.mjs --check   # compare only; exit 1 on drift, never write
//
// Checkout locations default to ~/finddata/<repo>; override with
// WIRE_OPS_MCP_DIR / WIRE_BUILD_MCP_DIR.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SNAPSHOT_PATH = resolve(here, "..", "lib", "wire-tool-risk.js");

export const SOURCE_REPOS = Object.freeze([
  { server: "wire-ops-mcp", envVar: "WIRE_OPS_MCP_DIR" },
  { server: "wire-build-mcp", envVar: "WIRE_BUILD_MCP_DIR" },
]);

// paas action id → wire operation-MCP tool name. Mirrors fd-wire's
// ACTION_TO_TOOL_NAME (api/fd_wire_api/ai/actions.py) plus the entry that map
// omits — wire.dataset.create — whose tool is nonetheless declared in
// wire-build-mcp's tool_risk. Only actions with a 1:1 tool carrier belong here;
// draft.create / promote / share.create / restore / update stay unmapped (see
// the change's design Open Questions).
export const WIRE_ACTION_TOOLS = Object.freeze({
  "wire.demand.submit": "wire_demand_submit",
  "wire.market.subscribe": "wire_market_subscribe",
  "wire.market.unsubscribe": "wire_market_unsubscribe",
  "wire.pack.subscribe": "wire_pack_subscribe",
  "wire.pack.unsubscribe": "wire_pack_unsubscribe",
  "wire.dataset.create": "wire_dataset_create",
  "wire.artifact.publish": "wire_artifact_publish",
  "wire.artifact.archive": "wire_artifact_archive",
  "wire.dataset.correct": "wire_dataset_correct",
  "wire.dataset.correction.revert": "wire_dataset_correction_revert",
});

export function sourceDir(repo, env = process.env) {
  return env[repo.envVar] || join(homedir(), "finddata", repo.server);
}

// Read both tool-surface.json files. Returns { tools: {name: {risk, server}}, missing: [server...] }.
export function readSourceToolRisk({ env = process.env } = {}) {
  const tools = {};
  const missing = [];
  for (const repo of SOURCE_REPOS) {
    const file = join(sourceDir(repo, env), "tool-surface.json");
    if (!existsSync(file)) {
      missing.push(repo.server);
      continue;
    }
    const surface = JSON.parse(readFileSync(file, "utf8"));
    const declaredServer = typeof surface.server === "string" ? surface.server : repo.server;
    if (declaredServer !== repo.server) {
      throw new Error(`${file}: server "${declaredServer}" does not match expected "${repo.server}"`);
    }
    const risk = surface.tool_risk;
    if (!risk || typeof risk !== "object" || Array.isArray(risk)) {
      throw new Error(`${file}: missing top-level tool_risk object`);
    }
    for (const [tool, level] of Object.entries(risk)) {
      if (tools[tool]) throw new Error(`tool "${tool}" declared by both ${tools[tool].server} and ${repo.server}`);
      tools[tool] = { risk: String(level), server: repo.server };
    }
  }
  return { tools, missing };
}

export function renderSnapshot(tools) {
  const sorted = Object.keys(tools).sort();
  const lines = [
    "// lib/wire-tool-risk.js — GENERATED by scripts/refresh-wire-tool-surface.mjs.",
    "// Do not hand-edit: rerun the script against the wire-ops-mcp / wire-build-mcp",
    "// checkouts. Source of truth = each repo's tool-surface.json `tool_risk`.",
    "// (add-wire-line-board, design D2)",
    "",
    "// Every tool the two wire operation servers declare, with its risk and",
    "// hosting server — a faithful mirror of the sources' `tool_risk`, `read`",
    "// included. The gated subset below (risk !== read) is the pack publish",
    "// lint's write-tool blocklist.",
    "export const WIRE_TOOL_RISK = Object.freeze({",
  ];
  for (const name of sorted) {
    lines.push(`  ${name}: Object.freeze({ risk: "${tools[name].risk}", server: "${tools[name].server}" }),`);
  }
  lines.push("});", "");
  lines.push("// paas action id → tool name (1:1 carriers only; mirrors fd-wire ACTION_TO_TOOL_NAME + wire.dataset.create).");
  lines.push("export const WIRE_ACTION_TOOLS = Object.freeze({");
  for (const [action, tool] of Object.entries(WIRE_ACTION_TOOLS)) {
    lines.push(`  "${action}": "${tool}",`);
  }
  lines.push("});", "");
  lines.push("// The gated universe: every declared tool whose risk is not `read`.");
  lines.push("// Read stays outside the gate (its tier is auto), so mirroring those names");
  lines.push("// here would be a real defect, not bookkeeping: a pack that declares a");
  lines.push("// read-only tool is a read face, and isWireWriteTool() on that name would");
  lines.push("// refuse it outright.");
  lines.push("export const WIRE_WRITE_TOOLS = Object.freeze(");
  lines.push("  Object.keys(WIRE_TOOL_RISK).filter((tool) => WIRE_TOOL_RISK[tool].risk !== \"read\").sort(),");
  lines.push(");", "");
  lines.push("export function riskForTool(tool) {", "  return WIRE_TOOL_RISK[tool]?.risk ?? null;", "}", "");
  lines.push("export function serverForTool(tool) {", "  return WIRE_TOOL_RISK[tool]?.server ?? null;", "}", "");
  lines.push("export function toolForAction(actionId) {", "  return WIRE_ACTION_TOOLS[actionId] ?? null;", "}", "");
  lines.push("export function isWireWriteTool(tool) {");
  lines.push("  const risk = WIRE_TOOL_RISK[tool]?.risk;");
  lines.push("  return Boolean(risk) && risk !== \"read\";");
  lines.push("}", "");
  return lines.join("\n");
}

export function currentSnapshot() {
  return existsSync(SNAPSHOT_PATH) ? readFileSync(SNAPSHOT_PATH, "utf8") : null;
}

function diffSummary(before, after) {
  const a = (before || "").split("\n");
  const b = after.split("\n");
  const out = [];
  const max = Math.max(a.length, b.length);
  for (let i = 0; i < max; i++) {
    if (a[i] !== b[i]) {
      if (a[i] !== undefined) out.push(`- ${a[i]}`);
      if (b[i] !== undefined) out.push(`+ ${b[i]}`);
    }
  }
  return out.join("\n");
}

async function main() {
  const check = process.argv.includes("--check");
  const { tools, missing } = readSourceToolRisk();
  if (missing.length) {
    console.error(`[refresh-wire-tool-surface] missing checkout(s): ${missing.join(", ")} — set WIRE_OPS_MCP_DIR / WIRE_BUILD_MCP_DIR`);
    process.exit(3);
  }
  for (const [action, tool] of Object.entries(WIRE_ACTION_TOOLS)) {
    if (!tools[tool]) {
      console.error(`[refresh-wire-tool-surface] action ${action} maps to ${tool}, which no source tool_risk declares`);
      process.exit(4);
    }
  }
  const rendered = `${renderSnapshot(tools)}\n`;
  const before = currentSnapshot();
  if (before === rendered) {
    console.log(`[refresh-wire-tool-surface] snapshot up to date (${Object.keys(tools).length} write tools, ${Object.keys(WIRE_ACTION_TOOLS).length} actions)`);
    return;
  }
  console.log(`[refresh-wire-tool-surface] snapshot ${before === null ? "created" : "changed"}:`);
  console.log(diffSummary(before, rendered));
  if (check) {
    console.error("[refresh-wire-tool-surface] --check: drift detected, not writing");
    process.exit(1);
  }
  writeFileSync(SNAPSHOT_PATH, rendered);
  console.log(`[refresh-wire-tool-surface] wrote ${SNAPSHOT_PATH} — review and commit`);
  process.exit(2);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch((err) => {
    console.error(`[refresh-wire-tool-surface] ${err.message}`);
    process.exit(1);
  });
}
