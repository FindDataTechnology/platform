// platform-preset-bridge.js — the platform profile's SDK JSON-RPC server.
//
// Subclasses the stock @deepseek-ai/dsh-sdk-jsonrpc-server plugin to add the
// three things the platform host needs that the stock server does not carry:
//
//   1. `initialize` accepts `agentPreset` (the deployment-selected agent mode).
//   2. Lazily-created sessions compose that preset: `createSession` calls
//      `agents.create` itself (duplicating the parent's ~8-line call) with a
//      `setup(agentCtx)` hook that runs `agentPresets.mount(agentCtx, id)` —
//      the one supported mount call site, so a broken or unknown preset fails
//      session creation BEFORE the agent is published (the factory rolls the
//      whole creation back). The preset id is also recorded on the session
//      header (`meta.agentPreset`) so the session's log names the composition
//      it started with. No roster composed → session creation is delegated to
//      the parent unchanged (bare host composition).
//   3. A `presets/list` JSON-RPC method returns the serialized roster
//      (id/name/description/trust/broken) for the web picker.
//   4. Live runtime control (live-runtime-control): `model/set` flips a live
//      per-agent model selection (installModelSelection — a mid-run switch
//      takes effect on the next step, never tearing the in-flight request),
//      `session/cancel` aborts a session's active turn natively
//      (agent.cancel + whenIdle), and `tools/set` flips a per-session MCP
//      server gate default-closed (websearch) through the guard layer.
//      `platform/capabilities` reports the method set so the host can degrade
//      to its legacy restart paths against an older child.
//      `preset/set` (add-dsh-pod-adapter) parks a per-session preset choice:
//      pod-mode hosts select each member's persona before the session's first
//      prompt; creation composes the parked preset (parked → initialize-time
//      agentPreset → registry default). Parked-only by design — the supported
//      mount point is creation-time setup, so a live session's preset is
//      refused explicitly (start a new session), never silently swapped.
//   5. Stream forward (restore-assistant-stream-020): the 0.2.0 session
//      format dropped `assistant/chunk` from session.event — the live token
//      stream rides the process-wide `agent/assistant-stream` ctx channel.
//      Every frame is forwarded to the host as a `platform/stream`
//      notification (same child→host lane as userQuestion/ask), keyed by the
//      streaming session; `platform/capabilities` reports `streamForward`
//      so the host knows the delta lane is live (and gates its settled-text
//      fallback off it).
//
// Loaded by presets.patch.yml (generated by the host's dsh-profile.js), which
// disables the stock `sdk-jsonrpc-server` row and inserts this plugin under a
// fresh row id. Its imports resolve through the profile's node_modules walk
// (the profile pins dsh-agent-presets; dsh-sdk-jsonrpc-server is linked there)
// — except dsh-sdk-protocol, which ships as a PRIVATE dependency of the SDK
// server package, so it is resolved through that package's real location.

import { createRequire } from "node:module";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import Schema from "@deepseek-ai/schemastery";
import { SessionId } from "@deepseek-ai/dsh-session";
import { HarnessSdkJsonRpcServer } from "@deepseek-ai/dsh-sdk-jsonrpc-server";
import {
  applyMcpToolRestrict,
  installMcpToolGuard,
  installMcpToolRegisterShadow,
  installSessionToolGate,
  setSessionToolGate,
} from "./platform-tool-scope.js";

// JsonRpcLineTransport lives in the SDK server package's own dependency
// closure. Re-anchor resolution at the server package's entry file (its real
// path — Node resolves symlinks), where the protocol package is reachable.
const transport = await (async () => {
  const serverRequire = createRequire(
    import.meta.resolve("@deepseek-ai/dsh-sdk-jsonrpc-server"),
  );
  const protocolDir = join(
    serverRequire.resolve("@deepseek-ai/dsh-sdk-protocol/package.json"),
    "..",
  );
  return import(pathToFileURL(join(protocolDir, "lib", "index.js")));
})();
const { JsonRpcLineTransport } = transport;

const name = "platform-sdk-server";
const inject = ["agents", "tools"];
const Config = Schema.object({ maxTokensAsSuccess: Schema.boolean().default(false) });

class PlatformSdkServer extends HarnessSdkJsonRpcServer {
  agentPresetId = null;

  // ── Live runtime control (live-runtime-control) ────────────────────────────
  // Custom RPC methods this bridge adds over the stock 3-RPC SDK surface. The
  // host probes `platform/capabilities` once per spawn and degrades to the
  // legacy restart paths when the method set is missing (older child).
  static LIVE_METHODS = ["model/set", "session/cancel", "tools/set", "preset/set"];
  // installModelSelection refs by dsh session id — the mutable model selection
  // a `model/set` flips. Populated as sessions are (lazily) created.
  #selections = new Map();
  // Selections parked for session ids the child has not created yet (the host
  // may switch models before the first prompt of a session).
  #pendingSelections = new Map();
  // Preset ids parked for session ids the child has not created yet
  // (add-dsh-pod-adapter: `preset/set`). Taken (once) at creation — the same
  // parked-then-seeded shape model selections use, for the persona dimension.
  #pendingPresets = new Map();
  // Provider-default thinking level carried across model/set calls (null =
  // provider default). Mirrors the host's persisted per-provider effort.
  #defaultEffort = null;
  // MCP servers under a per-session on/off gate, default closed. Declared by
  // the host at initialize (sessionGatedMcp); the platform default is websearch.
  #gatedServers = ["websearch"];

  constructor(ctx, transport, options) {
    super(ctx, transport, options);
    // Stream forward (restore-assistant-stream-020): same registration shape
    // the base class itself uses for session/event — a constructor-time
    // registration on the server's ctx hears every lazily-created agent's
    // frames. (An apply-time ctx.effect registration was proven deaf to these
    // scope-filtered agent events in the census harness — constructor-only.)
    this.disposers.push(
      ctx.on("agent/assistant-stream", ({ agent, frame }) => {
        const sessionId = agent?.session?.id;
        if (sessionId === undefined || frame === undefined) return;
        this.transport.notify("platform/stream", { sessionId: String(sessionId), frame });
      }),
    );
  }

  async initialize(params) {
    this.agentPresetId =
      typeof params?.agentPreset === "string" && params.agentPreset
        ? params.agentPreset
        : null;
    if (Array.isArray(params?.sessionGatedMcp)) {
      this.#gatedServers = params.sessionGatedMcp.filter((s) => typeof s === "string" && s);
    }
    return super.initialize(params);
  }

  // Per-agent options are identical for create and resume, so a restart that
  // also switched the model resumes the old conversation on the NEW model.
  #agentOptions() {
    return {
      provider: this.provider,
      model: this.model,
      ...(this.maxTokens === undefined ? {} : { maxTokens: this.maxTokens }),
    };
  }

  // Does this session id already own a persisted log? The profile's
  // persistence service answers — with the seam THIS dsh generation actually
  // exposes. 0.2.0 renamed the probe face: `loadStored` is gone (only
  // loadStoredMigration survives) and `stat(id)` is the native existence
  // probe ({header,…} for a stored session, undefined otherwise). Probing the
  // dead name degraded silently to "not persisted", so a restarted child took
  // the CREATE path for an id the store had already hydrated — the late
  // "session … already exists" collision (live pod validation 2026-10-14:
  // a rebuilt pod's first turn died exactly there). A missing service or a
  // probe failure still degrades to "not persisted": callers then take the
  // stock create path exactly as they did before this bridge learned to
  // resume.
  async #isPersisted(sessionId) {
    const persistence = this.ctx.get("sessionPersistence");
    if (persistence === undefined) return false;
    try {
      if (typeof persistence.stat === "function") {
        return (await persistence.stat(SessionId(sessionId))) !== undefined;
      }
      if (typeof persistence.loadStored === "function") {
        return (await persistence.loadStored(SessionId(sessionId))) !== undefined;
      }
      return false;
    } catch {
      return false;
    }
  }

  // Lazily create — or RESUME — one session. After a child restart (model /
  // workspace switch, MCP hot-swap fallback, crash) the platform keeps
  // prompting session ids whose logs are already on disk. Creating those fresh
  // is rejected by dsh's persistence layer, and it rejects LATE (at the first
  // append, as an id-collision turn error), so "create, then recover" is not
  // available: the stored log has to be probed FIRST and the session resumed
  // instead. Resume takes the same preset mount through its own
  // pre-publication setup hook, so a resumed agent is composed identically.
  // Public createSession: the stock body (below) plus live-control attachment
  // for EVERY creation path (roster-composed, stock-delegated, resume). The
  // attachment installs the per-agent mutable model selection (`model/set`)
  // and the per-agent session tool gate (`tools/set`) on the agent's scoped
  // context; both unwind with the agent scope on disposal.
  async createSession(sessionId) {
    const rec = await this.#createSessionInner(sessionId);
    this.#attachLiveControl(sessionId, rec);
    return rec;
  }

  // Couple one agent to the platform's live-control surfaces. Failure-isolated:
  // a missing export or a reshaped internal seam logs and degrades — the agent
  // keeps its creation-time options and the caller's RPCs report unsupported.
  #attachLiveControl(sessionId, rec) {
    const agent = rec?.handle?.agent;
    const agentCtx = agent?.ctx;
    if (!agentCtx) return;
    // Model selection: a mutable ref the model/set RPC flips, applied by an
    // agent/request waterfall reading the ref's CURRENT value — request
    // granularity is the honest step boundary (a request already sent is
    // untouched; the next request picks the new pair up). dsh's own
    // installModelSelection chain is NOT used for this: its agent/request leg
    // applies the value the system-prompt assembly snapshotted
    // (selection.assembled), and SDK-created agents cache that assembly per
    // session — a later flip would never re-snapshot (contract ⑦ evidence).
    // The effort semantics mirror dsh's: absent clears any inherited level.
    const ref = { current: null };
    try {
      agentCtx.on("agent/request", async (_payload, next) => {
        const resolved = await next();
        const sel = ref.current;
        if (!sel) return resolved;
        const { reasoningEffort: _inherited, ...rest } = resolved;
        return {
          ...rest,
          provider: sel.provider,
          model: sel.model,
          ...(sel.reasoningEffort === undefined ? {} : { reasoningEffort: sel.reasoningEffort }),
        };
      });
      // A selection parked by model/set BEFORE this session existed seeds the
      // ref now — the agent's first request already runs on it.
      const parked = this.#pendingSelections.get(sessionId);
      if (parked) {
        ref.current = {
          provider: parked.provider,
          model: parked.model,
          ...(parked.effort ? { reasoningEffort: parked.effort } : {}),
        };
        this.#pendingSelections.delete(sessionId);
      }
      this.#selections.set(sessionId, ref);
    } catch (err) {
      this.ctx.logger?.warn?.(
        `platform-sdk-server: agent/request model-selection failed for ${sessionId}; model/set degrades to new-session defaults (${err?.message || err})`,
      );
    }
    if (this.#gatedServers.length) {
      try {
        installSessionToolGate(agentCtx, sessionId, this.#gatedServers);
      } catch (err) {
        this.ctx.logger?.warn?.(
          `platform-sdk-server: session tool gate failed for ${sessionId}; gated servers stay enforceable only if enabled by default (${err?.message || err})`,
        );
      }
    }
  }

  async #createSessionInner(sessionId) {
    const presets = this.ctx.get("agentPresets");
    const persisted = await this.#isPersisted(sessionId);
    if (presets === undefined) {
      // No roster composed. A fresh id still goes through the stock create; a
      // persisted one has no stock resume equivalent, so resume directly.
      if (!persisted) return super.createSession(sessionId);
      const resumed = {
        handle: await this.ctx.agents.resume({
          resumeSessionId: SessionId(sessionId),
          agentOptions: this.#agentOptions(),
        }),
      };
      this.sessions.set(sessionId, resumed);
      return resumed;
    }
    // Resolve before creation so an unknown id fails before any session or
    // agent state exists; mount in setup so a broken composition rolls the
    // whole creation back instead of publishing a half-composed agent.
    // A preset parked by `preset/set` wins over the initialize-time default
    // (add-dsh-pod-adapter) — pod hosts select each member's persona here.
    // The take is single-shot: a parked id survives only the creation it was
    // meant to steer, never a later re-creation of the same id.
    // After the mount, the focused role's MCP tool allowlist narrows the
    // agent's roster (add-mcp-tool-scoping D2) — best-effort; the global
    // guard installed in apply() carries the hard interception regardless.
    const parkedPreset = this.#pendingPresets.get(sessionId);
    if (parkedPreset !== undefined) this.#pendingPresets.delete(sessionId);
    const preset = await presets.resolve(parkedPreset ?? this.agentPresetId ?? undefined);
    const setup = async (agentCtx) => {
      await presets.mount(agentCtx, preset.id);
      applyMcpToolRestrict(agentCtx, preset.id);
    };
    const handle = persisted
      ? await this.ctx.agents.resume({
          resumeSessionId: SessionId(sessionId),
          agentOptions: this.#agentOptions(),
          setup,
        })
      : await this.ctx.agents.create({
          sessionId: SessionId(sessionId),
          meta: { cwd: this.cwd, agentPreset: preset.id },
          agentOptions: this.#agentOptions(),
          setup,
        });
    const rec = { handle };
    this.sessions.set(sessionId, rec);
    return rec;
  }

  // `model/set { sessionId?, provider, model, reasoningEffort? }` — flip the
  // live model selection. With a sessionId that has a live agent, the flip
  // takes effect on the agent's next model request (dsh snapshots the current
  // step's selection, so an in-flight request is never torn). Without one (or
  // for a not-yet-created session) it updates the process defaults every NEW
  // session composes with — the host's switch-the-active-model semantics.
  // NOTE: a sessionId-carrying call ALSO flips those process defaults (the
  // switch-the-active-model side effect); pod hosts therefore park BOTH
  // dimensions (preset/set + model/set) for EVERY member session before its
  // first prompt, so a default flipped by one member's park never decides
  // another session's composition (contract ⑯ pins the live-sibling half).
  // The effort field: undefined = keep the selection's current level, "" or null =
  // clear to the provider default, otherwise the named level.
  async #rpcModelSet(params) {
    const provider = typeof params?.provider === "string" ? params.provider.trim() : "";
    const model = typeof params?.model === "string" ? params.model.trim() : "";
    if (!provider || !model) throw new Error("model/set requires string provider and model");
    if (!this.hasAdapterFor(provider)) {
      throw new Error(`no adapter registered for provider "${provider}"`);
    }
    const rawEffort = params?.reasoningEffort;
    const effort = rawEffort === undefined ? undefined : rawEffort ? String(rawEffort) : null;
    this.provider = provider;
    this.model = model;
    if (effort !== undefined) this.#defaultEffort = effort;
    const sessionId = typeof params?.sessionId === "string" && params.sessionId ? params.sessionId : null;
    if (!sessionId) return { ok: true };
    const ref = this.#selections.get(sessionId);
    if (ref) {
      const prevEffort = ref.current?.reasoningEffort;
      const nextEffort = effort === undefined ? prevEffort : effort || undefined;
      ref.current = { provider, model, ...(nextEffort ? { reasoningEffort: nextEffort } : {}) };
      // `applied` names whether a live selection existed (false = parked for
      // creation); the next request of this session runs the new pair.
      return { ok: true, applied: true };
    }
    this.#pendingSelections.set(sessionId, { provider, model, effort: effort === undefined ? this.#defaultEffort : effort });
    return { ok: true, applied: false };
  }

  // `preset/set {sessionId, presetId}` (add-dsh-pod-adapter) — park the
  // per-session persona choice for a session the child has not created yet;
  // the session's (lazy) creation composes it (parked → initialize-time
  // agentPreset → registry default), and the session header names the preset
  // actually mounted. A session that already exists — or is being created
  // right now — is refused explicitly: the supported mount point is
  // creation-time setup, so changing a live session's persona means starting
  // a new session, never a silent swap (or a silently ignored call).
  async #rpcPresetSet(params) {
    const sessionId = typeof params?.sessionId === "string" ? params.sessionId : "";
    const presetId = typeof params?.presetId === "string" ? params.presetId.trim() : "";
    if (!sessionId || !presetId) throw new Error("preset/set requires string sessionId and presetId");
    if (this.sessions.has(sessionId) || this.sessionCreations?.has(sessionId)) {
      throw new Error(
        `preset/set refused for session '${sessionId}': persona is creation-time composition — start a new session to change presets`,
      );
    }
    this.#pendingPresets.set(sessionId, presetId);
    return { ok: true };
  }

  // `session/cancel { sessionId }` — abort the session's active turn via dsh's
  // native agent.cancel, converging on whenIdle (bounded: the host's finishTurn
  // also fires from the session.status idle notification, so a slow drain never
  // wedges the stop). A session with no live agent (never created, or idle) is
  // a successful no-op.
  async #rpcSessionCancel(params) {
    const sessionId = typeof params?.sessionId === "string" ? params.sessionId : "";
    if (!sessionId) throw new Error("session/cancel requires a sessionId");
    const rec = this.sessions.get(sessionId);
    const agent = rec?.handle?.agent;
    if (!agent || typeof agent.cancel !== "function") return { ok: true, noop: true };
    agent.cancel({ kind: "user" });
    try {
      await Promise.race([
        agent.whenIdle(),
        new Promise((resolve) => setTimeout(resolve, 10_000)),
      ]);
    } catch {
      /* convergence reporting only — the cancel itself already happened */
    }
    return { ok: true };
  }

  // `tools/set { sessionId, server, enabled }` — flip a per-session MCP server
  // gate (see platform-tool-scope). Takes effect on the next tool call; a
  // session not yet created gets the flip through the shared gate map its
  // agent's guard will read once composed.
  async #rpcToolsSet(params) {
    const sessionId = typeof params?.sessionId === "string" ? params.sessionId : "";
    const server = typeof params?.server === "string" ? params.server.trim() : "";
    if (!sessionId || !server || typeof params?.enabled !== "boolean") {
      throw new Error("tools/set requires sessionId, server and boolean enabled");
    }
    setSessionToolGate(sessionId, server, params.enabled);
    return { ok: true };
  }

  async handleRequest(method, params) {
    if (method === "platform/capabilities") {
      return { methods: [...PlatformSdkServer.LIVE_METHODS], streamForward: true };
    }
    if (method === "model/set") return this.#rpcModelSet(params);
    if (method === "session/cancel") return this.#rpcSessionCancel(params);
    if (method === "tools/set") return this.#rpcToolsSet(params);
    if (method === "preset/set") return this.#rpcPresetSet(params);
    if (method === "presets/list") {
      const presets = this.ctx.get("agentPresets");
      if (presets === undefined) return [];
      const rows = await presets.list();
      return rows.map((p) => ({
        id: p.id,
        name: p.name ?? p.id,
        description: p.description ?? "",
        // The 0.2.0 declarative registry has no trust dimension (no directory
        // discovery); every platform-composed row is platform-provided.
        trust: p.trust ?? "system",
        ...(p.broken === undefined ? {} : { broken: p.broken }),
      }));
    }
    return super.handleRequest(method, params);
  }
}

// Wiring identical to the stock plugin's apply — the only change is the server
// class. Stdout stays reserved for protocol frames; `shutdown` disposes the
// SDK-created agents and exits 0.
function apply(ctx, config) {
  const resolvedConfig = config;
  const rootFiber = ctx.root.fiber;
  // Global tool-allowlist guard (add-mcp-tool-scoping D2): plain-context, so
  // it covers the session agent AND every delegated child in this process.
  // No-ops when no filter is materialized (full mode / legacy packs).
  installMcpToolGuard(ctx);
  // Registration-time dropping (add-tool-scope-register-shadow D2): must run
  // at plugin start, BEFORE dsh-mcp-client's rows register their first
  // generation — the presets patch is ordered ahead of mcp.patch.yml for
  // exactly this reason (a late shadow misses the first generation and only
  // the guard/restrict layers would remain).
  installMcpToolRegisterShadow(ctx);
  const input = config.input ?? process.stdin;
  const output = config.output ?? process.stdout;
  const exit = config.exit ?? ((code) => process.exit(code));
  const transportPeer = new JsonRpcLineTransport(input, output);
  const server = new PlatformSdkServer(ctx, transportPeer, {
    maxTokensAsSuccess: resolvedConfig.maxTokensAsSuccess,
  });
  let exitTask;
  const disposeAndExit = () => {
    exitTask ??= (async () => {
      await Promise.allSettled([Promise.resolve().then(() => transportPeer.flush())]);
      await Promise.allSettled([Promise.resolve().then(() => rootFiber.dispose())]);
      exit(0);
    })();
    return exitTask;
  };
  transportPeer.onRequest(async (method, params) => {
    const result = await server.handleRequest(method, params);
    if (method === "shutdown") {
      setImmediate(() => disposeAndExit());
    }
    return result;
  });
  ctx.effect(() => {
    transportPeer.start();
    return async () => {
      await server.shutdown();
      transportPeer.close();
    };
  }, "jsonrpc.serve");
}

export { Config, PlatformSdkServer, apply, inject, name };
